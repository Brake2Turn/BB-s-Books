import { chromium } from './pw.mjs';
import { coverSvg } from './mockcovers.mjs';
const S = process.argv[2] || new URL('./.fixtures', import.meta.url).pathname; // test images and screenshots
const b = await chromium.launch();
const errors = [];
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, serviceWorkers: 'block' });
await ctx.route(/covers\.openlibrary\.org\/b\/isbn\/(\d+)/, (r) => {
  const isbn = r.request().url().match(/isbn\/(\d+)/)[1];
  if (Number(isbn.slice(-2)) % 3 === 0) return r.fulfill({ status: 404, body: '' });
  r.fulfill({ body: coverSvg(isbn), contentType: 'image/svg+xml' });
});
let posted = null; let fail = false;
await ctx.route('https://formsubmit.co/**', (r) => {
  posted = { url: r.request().url(), body: JSON.parse(r.request().postData()) };
  if (fail) return r.fulfill({ status: 500, json: { success: 'false', message: 'down' } });
  r.fulfill({ json: { success: 'true', message: 'The form was submitted successfully.' } });
});
await ctx.addInitScript(() => document.addEventListener('DOMContentLoaded', () => document.getElementById('splash')?.remove()));
  const p = await ctx.newPage();
p.on('pageerror', (e) => errors.push(e.message));
p.on('console', (m) => { if (m.type() === 'error' && !/404|500/.test(m.text())) errors.push(m.text()); });
await p.goto('http://localhost:8123/?demo');
await p.waitForTimeout(1200);
await p.screenshot({ path: `${S}/F-home.png` });
await p.mouse.wheel(0, 700); await p.waitForTimeout(400);
await p.screenshot({ path: `${S}/F-home-scrolled.png` });
await p.mouse.wheel(0, -2000);
await p.fill('#search', 'miller');
await p.waitForTimeout(300);
console.log('search count:', String(await p.locator('#libraryShelves .book').count()) + ' books shown');
await p.fill('#search', '');
await p.selectOption('#statusFilter', 'read');
console.log('finished count:', String(await p.locator('#libraryShelves .book').count()) + ' books shown');
await p.selectOption('#statusFilter', '');
console.log('header profile buttons:', await p.locator('.app-header button').count(), '| tabs:', await p.locator('.tabbar [aria-label]').evaluateAll(n => n.map(x => x.getAttribute('aria-label')).join(', ')));
await p.click('.tab[data-go="feedback"]');
await p.waitForTimeout(300);
await p.click('#fbSend');
console.log('empty send:', await p.textContent('#fbStatus'), '| posted?', !!posted);
await p.fill('#fbMessage', 'Could the stats show books finished per month?');
await p.fill('#fbName', 'BB');
await p.screenshot({ path: `${S}/F-feedback.png` });
await p.click('#fbSend');
await p.waitForTimeout(400);
console.log('posted to:', posted.url); console.log('body:', JSON.stringify(posted.body));
console.log('after send, message cleared:', (await p.inputValue('#fbMessage')) === '', '| toast:', await p.textContent('#toast'));
await p.screenshot({ path: `${S}/F-sent.png` });
fail = true;
await p.fill('#fbMessage', 'second');
await p.click('#fbSend');
await p.waitForTimeout(400);
console.log('on failure:', await p.textContent('#fbStatus'), '| message kept:', await p.inputValue('#fbMessage'));
await p.click('.tab[data-go="profile"]'); await p.click('[data-go="stats"]');
await p.screenshot({ path: `${S}/F-stats.png` });
console.log('errors:', errors);
await b.close();
